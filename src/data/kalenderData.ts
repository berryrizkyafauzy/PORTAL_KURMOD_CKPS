// Local storage key for persistent user-entered 2027 training records
export const STORAGE_KEY_2027 = 'cmrc_kalender_bangkom_2027';

export const getSavedKalender2027 = (): KalenderTrainingItem[] => {
  if (typeof window === 'undefined') return DEFAULT_KALENDER_PELATIHAN_2027;
  try {
    const raw = localStorage.getItem(STORAGE_KEY_2027);
    if (!raw) return DEFAULT_KALENDER_PELATIHAN_2027;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    return DEFAULT_KALENDER_PELATIHAN_2027;
  } catch (e) {
    console.error('Error loading 2027 kalender data:', e);
    return DEFAULT_KALENDER_PELATIHAN_2027;
  }
};

export const saveKalender2027 = (items: KalenderTrainingItem[]): void => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY_2027, JSON.stringify(items));
  } catch (e) {
    console.error('Error saving 2027 kalender data:', e);
  }
};

